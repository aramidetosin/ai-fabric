#!/bin/bash
# bastion-dns.sh: write BIND config + every zone file from the environment; the caller starts or reloads named.
# Split out of bastion-init.sh so the same code can refresh DNS on a RUNNING bastion (docker cp + docker exec + rndc reload).
# Needs: DOMAIN CLUSTER_NAME API_VIP GW_VIP BASTION_IP NODE_HOSTS FABRIC_CIDR ; optional MGMT_CIDR EXTRA_QUERY_CIDRS EXTRA_PTRS PC_IP PC_NAME DNS_FORWARDERS
# NO `set -u` / `set -e` here on purpose: bastion-init.sh SOURCES this file and runs under `set +e` with unguarded
# ${MGMT_IP} / ${GW_VIP} references after the source point. An unbound variable under `set -u` is fatal in bash even
# with `set +e`, so enabling it here would kill PID 1 of the bastion halfway through its startup.
rev() { local ip=$1; IFS=. read -r a b c d <<< "$ip"; echo "$c.$b.$a.in-addr.arpa"; }
SERIAL=$(date +%Y%m%d01)
# Clients live on more than the fabric: the firewall's management plane asks from the clab management network (it resolves the
# addresses in its traffic log by reverse DNS), so BIND listens on every address the bastion has and the ACL lists each client
# network explicitly. EXTRA_QUERY_CIDRS adds any others the profile needs.
ACL="localhost; ${FABRIC_CIDR}; ${MGMT_CIDR:-172.21.21.0/24};"
for c in ${EXTRA_QUERY_CIDRS:-}; do ACL="${ACL} ${c};"; done
cat > /etc/bind/named.conf.options <<EOF
options {
    directory "/var/cache/bind";
    listen-on { any; };
    listen-on-v6 { none; };
    allow-query { ${ACL} };
    recursion yes;
    allow-recursion { ${ACL} };
    forwarders { ${DNS_FORWARDERS:-8.8.8.8; 1.1.1.1;} };
    forward only;
    allow-transfer { none; };
    dnssec-validation no;
};
EOF
cat > /etc/bind/named.conf.local <<EOF
// ai-fabric lab zone for cluster ${CLUSTER_NAME} (reference-style: api -> control-plane VIP, *.platform -> gateway VIP)
zone "${DOMAIN}" { type master; file "/etc/bind/zones/db.${DOMAIN}"; notify no; allow-transfer { none; }; };
EOF
# Every PTR the bastion serves, as "ip=name" pairs, grouped into one reverse zone per distinct /24 (REFPLAT: nodes and bastion
# share 10.78.112.0/26, so the grouping -- not a fixed list of subnets -- is what decides the zones). EXTRA_PTRS carries whatever
# the profile adds beyond the nodes: OOB/BMC addresses, the enterprise PC subnets, the device management network, the office LAN.
# Note the trade-off: the bastion becomes authoritative for each of these /24s, so an address in one that is NOT listed here
# answers NXDOMAIN instead of being forwarded. Only put subnets the lab owns in EXTRA_PTRS.
PTRS=("${API_VIP}=api" "${BASTION_IP}=bastion")
for kv in ${NODE_HOSTS:-}; do PTRS+=("${kv#*=}=${kv%%=*}"); done
[ -n "${PC_IP:-}" ] && PTRS+=("${PC_IP}=${PC_NAME:-pc}")
for kv in ${EXTRA_PTRS:-}; do PTRS+=("$kv"); done
declare -A ZONE
for kv in "${PTRS[@]}"; do z=$(rev "${kv%%=*}"); ZONE[$z]="${ZONE[$z]:-} $kv"; done
for z in $(printf '%s\n' "${!ZONE[@]}" | sort); do
  echo "zone \"${z}\" { type master; file \"/etc/bind/zones/db.${z}\"; notify no; allow-transfer { none; }; };" >> /etc/bind/named.conf.local
done
{
  echo "; Forward zone for ${DOMAIN} -- generated by bastion-init.sh"
  echo "\$ORIGIN ${DOMAIN}."
  echo "\$TTL 3600"
  echo "@   IN  SOA ns.${DOMAIN}. hostmaster.${DOMAIN}. ( ${SERIAL} 3600 600 604800 3600 )"
  echo "@   IN  NS  ns.${DOMAIN}."
  echo "ns  IN  A   ${BASTION_IP}"
  echo "; control-plane API endpoint -> kube-vip VIP"
  echo "api IN  A   ${API_VIP}"
  echo "; platform ingress wildcard: the Gateway address announced by Cilium"
  echo "*.platform IN A ${GW_VIP}"
  echo "bastion IN A ${BASTION_IP}"
  for kv in ${NODE_HOSTS:-}; do echo "${kv%%=*} IN A ${kv#*=}"; done
} > "/etc/bind/zones/db.${DOMAIN}"
mkrev() { # $1 zone name, then "ip=name" pairs; the first entry for an address wins, so a duplicate cannot emit two PTRs
  local z=$1; shift
  { echo "\$ORIGIN ${z}."; echo "\$TTL 3600"
    echo "@ IN SOA ns.${DOMAIN}. hostmaster.${DOMAIN}. ( ${SERIAL} 3600 600 604800 3600 )"
    echo "@ IN NS ns.${DOMAIN}."
    printf '%s\n' "$@" | awk -F= -v d="$DOMAIN" '$1 != "" && !seen[$1]++ { n = split($1, a, "."); print a[4], "IN PTR", $2 "." d "." }'
  } > "/etc/bind/zones/db.${z}"
}
for z in "${!ZONE[@]}"; do mkrev "$z" ${ZONE[$z]}; done
chown -R bind:bind /etc/bind/zones
