#!/usr/bin/env python3
"""make_xlsx.py: build the cabling workbook from the CSVs produced by gen_cabling.py.

One sheet per fabric plus a summary. Header frozen and filtered, columns sized to content, so the sheet is
usable for field work: sort by device, filter by speed, tick links off as they are patched.
"""
import csv, subprocess, sys
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

HDR_BG, HDR_FG = "1F3864", "FFFFFF"
BANDS = {"400G": "FFF2CC", "800G": "FCE4D6", "100G": "E2EFDA"}
thin = Side(style="thin", color="BFBFBF")

def rows_from(cmd):
    out = subprocess.run([sys.executable, "gen_cabling.py", cmd], capture_output=True, text=True, check=True).stdout
    return list(csv.reader(out.splitlines()))

def add_sheet(wb, title, rows, note):
    ws = wb.create_sheet(title)
    ws.append([note]); ws["A1"].font = Font(italic=True, color="595959")
    ws.append([])
    hdr_row = 3
    for r in rows:
        ws.append(r)
    for c, name in enumerate(rows[0], start=1):
        cell = ws.cell(row=hdr_row, column=c)
        cell.font = Font(bold=True, color=HDR_FG)
        cell.fill = PatternFill("solid", fgColor=HDR_BG)
        cell.alignment = Alignment(vertical="center")
    # colour each data row by link speed so the three link types are separable at a glance
    speed_col = rows[0].index("speed") + 1
    for r in range(hdr_row + 1, hdr_row + len(rows)):
        sp = ws.cell(row=r, column=speed_col).value
        fill = PatternFill("solid", fgColor=BANDS[sp]) if sp in BANDS else None
        for c in range(1, len(rows[0]) + 1):
            cell = ws.cell(row=r, column=c)
            cell.border = Border(bottom=thin)
            if fill: cell.fill = fill
    ws.freeze_panes = ws.cell(row=hdr_row + 1, column=1)
    ws.auto_filter.ref = f"A{hdr_row}:{get_column_letter(len(rows[0]))}{hdr_row + len(rows) - 1}"
    for c in range(1, len(rows[0]) + 1):
        width = max(len(str(ws.cell(row=r, column=c).value or "")) for r in range(hdr_row, hdr_row + len(rows)))
        ws.column_dimensions[get_column_letter(c)].width = min(width + 3, 62)
    return ws

be = rows_from("backend")
fe = rows_from("frontend")

wb = Workbook(); wb.remove(wb.active)
s = wb.create_sheet("Summary")
s.append(["production AI fabric - cabling matrix"]); s["A1"].font = Font(bold=True, size=15)
s.append(["Generated by gen_cabling.py from the decisions on diagrams/ai-fabric-32gpu.excalidraw."])
s.append(["Where the HLD still carries a <placeholder>, so does this workbook. Nothing here is invented."])
s.append([])
s.append(["fabric", "links", "detail"])
for c in range(1, 4):
    cell = s.cell(row=5, column=c); cell.font = Font(bold=True, color=HDR_FG); cell.fill = PatternFill("solid", fgColor=HDR_BG)
n400 = sum(1 for r in be[1:] if r[4] == "400G"); n800 = sum(1 for r in be[1:] if r[4] == "800G")
ngpu = sum(1 for r in fe[1:] if r[0].startswith("gpu")); nctl = len(fe) - 1 - ngpu
for row in [["Backend", len(be) - 1, f"{n400} x 400G GPU rails + {n800} x 800G leaf-spine uplinks"],
            ["Frontend", len(fe) - 1, f"{ngpu} x 100G GPU leaves + {nctl} x 100G control leaf pair"],
            ["TOTAL", len(be) - 1 + len(fe) - 1, "every GPU node: 8 x 400G backend rails + 2 x 100G frontend = 10 data links"]]:
    s.append(row)
s.cell(row=8, column=1).font = Font(bold=True); s.cell(row=8, column=2).font = Font(bold=True)
s.append([])
s.append(["Out of scope by request: border leaves, firewall, frontend leaf-spine uplinks (ports 31/32), OOB/BMC."])
s.append(["Open: ports 31/32 give 2 uplinks per leaf, while HLD decision 5 says 4 x 400G per leaf. To be reconciled."])
s.cell(row=11, column=1).font = Font(color="C00000")
for c, w in zip("ABC", (14, 10, 96)): s.column_dimensions[c].width = w

add_sheet(wb, "Backend", be,
          "Backend: GPU rails (rail-optimised, NIC r -> be-leaf r) and leaf-spine uplinks. Port numbering 0-based (UfiSpace S9321-64E).")
add_sheet(wb, "Frontend", fe,
          "Frontend servers: gpu1-16 on fe-gpu-leaf1/2, gpu17-32 on fe-gpu-leaf3/4, control leaf pair for ctrl1-6 + bastion + FlashBlade. "
          "Cisco Nexus Ethernet1/1..1/30 is the server range; 31 and 32 carry the spine uplinks.")
wb.save("ai-fabric-cabling.xlsx")
print("wrote ai-fabric-cabling.xlsx")
